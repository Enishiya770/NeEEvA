    private static int checks;
    private static void Check(bool value, string message)
    { checks++; if (!value) throw new InvalidOperationException("PCM lineage: " + message); }
    private static string Source(JObject lineage, int at = 0) => (string)lineage["regions"][at]["sourceId"];

    // Geometry and lyrics are from the immutable session's captures 7/17/22/23/24.
    // The source tokens are generated by the real recorder-lineage helper, not
    // inferred from similar Japanese ASR text. This is not a saved HTTP replay.
    public static RecordingSingingDecisionContext SessionContext(string user)
    {
        var lineage = new RecordingPcmLineage();
        lineage.Bind(23, 22, 7.98); lineage.Bind(24, 23, 14.22);
        var c = new RecordingSingingDecisionContext { UserText = user, RequireGroundedResolution = true,
            CurrentInput = new JObject { ["turn"] = 27, ["capture"] = 27, ["clip"] = "clip:test-27" },
            CurrentIntent = new JObject { ["roleProposal"] = new JObject { ["task"] = "recording_singing", ["goal"] = user } },
            Facts = "Actual ordered capture chronology: 7 first verse; 12..18 user introduces and records second verse; 20..21 introduces third verse, then 22..24 continues one recording. The ordinal song names here summarize retained user chronology, not capture numbers." };
        Add(c, lineage, 7, "此季哈哈利呀纳提嘎利。 私はどのんで。 思いやせる あなた の 姿。 いつ要かい理よ。", 0, 20.26, 25);
        Add(c, lineage, 17, "好吧，那看来这里还有点问题。接下来我唱第二段呃，现在我怎么唱来？ 別るく意味だ。 ならせめて悲しまないで。", 12.90, 22.67, 24.30);
        Add(c, lineage, 22, "Yes. 今からあなたのスへ。", 1.00, 6.47, 7.98);
        Add(c, lineage, 23, "信間からあなたのスへ 。", .37, 12.67, 14.22);
        Add(c, lineage, 24, "信間 から あなた の すえ。 哒。 好了，轮到你唱给我听了。", .37, 12.44, 16.94);
        return c;
    }

    private static void Add(RecordingSingingDecisionContext c, RecordingPcmLineage lineage, int capture,
        string transcript, double start, double end, double raw)
    {
        c.Materials.Add(new RecordingSingingMaterial { Key = "clip:test-" + capture, ClipRef = "clip:test-" + capture,
            CaptureSerial = capture, RecordingSequence = capture, Revision = "0", PlaybackStatus = "ready",
            HasCleanRange = true, HasExpandedRange = true,
            Description = new JObject { ["RecordingTranscript"] = transcript, ["SingingSegmentText"] = transcript,
                ["RawSeconds"] = raw, ["CleanStartSeconds"] = start, ["CleanEndSeconds"] = end,
                ["ExpandedStartSeconds"] = 0, ["ExpandedEndSeconds"] = raw,
                ["currentPlayback"] = new JObject { ["selected"] = true, ["CurrentStartSeconds"] = start, ["CurrentEndSeconds"] = end },
                ["pcmLineage"] = lineage.Describe(capture, raw) }.ToString(Formatting.None) });
    }

    private static JObject Plan(RecordingSingingDecisionContext c, string intent, params int[] captures)
    {
        var quote = RecordingSingingDecisionCompiler.QuoteReferences(c).OfType<JObject>().First(x => (string)x["origin"] == "current");
        return new JObject { ["decision"] = "perform", ["source_ref"] = quote["ref"], ["request_ref"] = "source",
            ["materials"] = new JArray(captures.Select(n => "clip:test-" + n)), ["range"] = "clean", ["intent"] = intent,
            ["expected"] = "按当前完整请求演唱所选录音", ["thought"] = "", ["speech"] = new JObject { ["text"] = "", ["language"] = "zh" },
            ["resolution"] = "matched", ["evidence_ref"] = "none", ["selection_evidence"] = new JArray(captures.Select(n => {
                var m = c.Materials.Single(x => x.CaptureSerial == n); string text = (string)JObject.Parse(m.Description)["RecordingTranscript"];
                return new JObject { ["key"] = m.Key, ["quote"] = text.Substring(0, Math.Min(40, text.Length)) }; })) };
    }

    public static int RunChecks()
    {
        checks = 0;
        var lineage = new RecordingPcmLineage(); var root = lineage.Describe(22, 7.98);
        lineage.Bind(23, 22, 7.98); lineage.Bind(24, 23, 14.22);
        var last = lineage.Describe(24, 16.94);
        Check(last["regions"].Count() == 3 && Source(last) == Source(root), "transitive prefix keeps original PCM source");
        Check((double)last["regions"][0]["rawEndSeconds"] == 7.98 && (double)last["regions"][1]["rawEndSeconds"] == 14.22,
            "session c22->23->24 copies precise recorder prefix lengths");
        Check(Source(lineage.Describe(25, 7.98)) != Source(root), "new independent user recording is not merged by duration/text");
        lineage.Bind(24, 24, 100); lineage.Bind(24, 23, double.NaN);
        Check(JToken.DeepEquals(last, lineage.Describe(24, 16.94)), "invalid/repeated binding cannot rewrite ancestry");
        lineage.Retire(22);
        Check(Source(lineage.Describe(22, 3)) != Source(root), "isolated suffix gets new PCM identity");
        Check(Source(lineage.Describe(24, 16.94)) == Source(root), "old descendant cannot acquire recreated parent identity");
        Check((bool)lineage.Describe(0, 3)["known"] == false && (bool)lineage.Describe(1, double.NaN)["known"] == false,
            "unknown duration/identity never creates provenance");

        var c = SessionContext("把第一段、第二段、第三段连起来唱给我听。");
        var coverage = RecordingSingingDecisionCompiler.ContinuationCoverageFacts(c);
        var links = (JArray)coverage["relations"];
        Check(links.Count == 2 && (string)links[0]["earlier"] == "clip:test-22" && (string)links[0]["later"] == "clip:test-23" &&
            (string)links[1]["earlier"] == "clip:test-23" && (string)links[1]["later"] == "clip:test-24", "coverage names nearest retained copied versions directly, without quadratic all-pair output");
        Check((bool)links[0]["rawIncludesEarlier"] && (double)links[0]["sharedRawSeconds"] == 7.98 &&
            (bool)links[1]["rawIncludesEarlier"] && (double)links[1]["sharedRawSeconds"] == 14.22, "raw coverage describes actual continuation prefixes rather than declaring complete verses");
        Check((string)links[0]["ranges"][0][1] == "later-includes-earlier" && (double)links[0]["ranges"][0][2] == 5.47,
            "third verse early clean window is visibly contained in the following retained version");
        Check((string)links[1]["ranges"][0][1] == "earlier-includes-later", "latest clean is slightly shorter despite raw extension, so no blind newest-is-fullest claim");
        var withoutMiddle = SessionContext(c.UserText); withoutMiddle.Materials.RemoveAll(m => m.CaptureSerial == 23);
        Check((string)RecordingSingingDecisionCompiler.ContinuationCoverageFacts(withoutMiddle)["relations"][0]["earlier"] == "clip:test-22",
            "missing intermediate retained clip still maps to known original capture without invented parent key");
        var longChain = new RecordingSingingDecisionContext(); var chain = new RecordingPcmLineage();
        for (int n = 1; n <= 32; n++) { if (n > 1) chain.Bind(n, n - 1, n); Add(longChain, chain, n, "independent semantic transcript", 0, n + 1, n + 1); }
        Check(RecordingSingingDecisionCompiler.ContinuationCoverageFacts(longChain)["relations"].Count() == 31,
            "long capture chain exports only linear predecessor facts");
        string schema = RecordingSingingDecisionCompiler.ResponseFormat(c).ToString();
        Check(schema.Contains("each array item plays ONCE") && schema.Contains("Only materials determines playback order and repetition count"),
            "real schema describes occurrence count instead of treating repeat intent as an implicit loop");
        bool Compile(JObject value, out string error) => RecordingSingingDecisionCompiler.TryCompile(value.ToString(), c, out _, out error);
        foreach (string range in new[] { "clean", "current", "expanded" })
        {
            var bad = Plan(c, "perform", 22, 23, 24); bad["range"] = range;
            Check(!Compile(bad, out var error) && error == "recording-overlapping-continuation-selection", "observed third-verse prefix aliases fail: " + range);
        }
        Check(Compile(Plan(c, "perform", 7, 17, 24), out _), "first plus second plus one third-verse version retain supported concat path");
        Check(Compile(Plan(c, "perform", 24), out _), "one complete third-verse source remains selectable");
        Check(!Compile(Plan(c, "perform", 24, 24), out _), "accidental repeated key needs explicit repeat intent");
        c.UserText = "把第三段同样的录音重复唱三遍。";
        Check(Compile(Plan(c, "repeat", 24, 24, 24), out _), "current explicit repeat keeps same-source repetitions possible");
        Check(RecordingSingingDecisionCompiler.TryCompile(Plan(c, "repeat", 24, 24, 24).ToString(), c, out string repeatedGoal, out _) &&
            repeatedGoal.Contains("refs=\"clip:test-24,clip:test-24,clip:test-24\""), "requested repeated occurrences survive to actual executable goal, not just schema acceptance");
        var sharedProof = Plan(c, "repeat", 24, 24, 24);
        sharedProof["selection_evidence"] = new JArray(sharedProof["selection_evidence"][0].DeepClone());
        Check(RecordingSingingDecisionCompiler.TryCompile(sharedProof.ToString(), c, out string sharedProofGoal, out _) &&
            sharedProofGoal.Contains("refs=\"clip:test-24,clip:test-24,clip:test-24\""),
            "one exact source proof supports repeated playback occurrences without changing execution count");
        Check(!Compile(Plan(c, "repeat", 22, 23, 24), out _), "repeat label cannot disguise different aliases as separate verses");
        var distinct = c.Materials.Single(m => m.CaptureSerial == 7); var original = distinct.Description;
        var changed = JObject.Parse(original); changed["RecordingTranscript"] = changed["SingingSegmentText"] = "信間からあなたのスへ 。";
        distinct.Description = changed.ToString();
        Check(Compile(Plan(c, "perform", 7, 23), out _), "identical words in independent user captures are not filtered");
        distinct.Description = original;
        var later = c.Materials.Single(m => m.CaptureSerial == 23); var laterFacts = JObject.Parse(later.Description);
        laterFacts["CleanStartSeconds"] = 7.98; later.Description = laterFacts.ToString();
        Check(Compile(Plan(c, "perform", 22, 23), out _), "nonoverlapping continuation suffix remains available");
        laterFacts.Remove("pcmLineage"); later.Description = laterFacts.ToString();
        Check(Compile(Plan(c, "perform", 22, 23), out _), "missing lineage stays unknown, never guessed from ASR similarity");
        var preserved = RecordingSingingDecisionCompiler.PromptFacts(c).ToString();
        Check(preserved.Contains("pcmLineage") && preserved.Contains("sourceId"), "production planner projection preserves copy geometry");

        byte[] a = Wav(8000, 3000), b = Wav(16000, 4000), cropped = Wav(16000, 1000);
        var buffers = new RecordingPcmLineage(); buffers.Bind(2, 1, 3);
        WaveformTrace.RegisterInputLineage(a, buffers.Describe(1, 3)); WaveformTrace.RegisterInputLineage(b, buffers.Describe(2, 4));
        Check(WaveformTrace.SharesCopiedPcm(a, 0, 3, b, 0, 4), "actual WAV provenance sees copied prefix despite different complete-buffer hashes");
        Check(!WaveformTrace.SharesCopiedPcm(a, 0, 3, b, 3, 4), "touching raw boundaries are not overlap");
        WaveformTrace.Transform(b, cropped, 1, 2);
        Check(WaveformTrace.SharesCopiedPcm(a, 1, 2, cropped, 0, 1), "trimmed/resampled source retains overlapping original coordinates");
        Check(!WaveformTrace.SharesCopiedPcm(a, 2, 3, cropped, 0, 1), "trimmed ranges outside source intersection remain allowed");
#if UNITY_EDITOR
        ProviderChecks();
#endif
        return checks;
    }

    public static void ExportCases(string output)
    {
        var cases = new JArray();
        foreach (string id in new[] { "third-verse-one-source", "three-distinct-verses", "explicit-third-repeat" })
        {
            string user = id == "third-verse-one-source" ? "是说唱出来了，不是抄出来，是唱出来，把第三段唱出来。" :
                id == "three-distinct-verses" ? "虽然不知道为什么你同样的旋律唱三遍。现在把第一段、第二段、第三段连起来唱给我听。" : "把第三段同样的录音重复唱三遍。";
            var c = SessionContext(user);
            cases.Add(new JObject { ["id"] = id, ["scope"] = "Log-derived capture prefixes, boundaries and ASR transcript; focused reconstructed context, not original HTTP packet or audio replay.",
                ["context"] = new JObject { ["UserText"] = c.UserText, ["Facts"] = c.Facts,
                    ["RequireGroundedResolution"] = c.RequireGroundedResolution, ["CurrentInput"] = c.CurrentInput.DeepClone(),
                    ["CurrentIntent"] = c.CurrentIntent.DeepClone(), ["Materials"] = new JArray(c.Materials.Select(m => new JObject {
                        ["Key"] = m.Key, ["ClipRef"] = m.ClipRef, ["Revision"] = m.Revision, ["Description"] = m.Description,
                        ["CaptureSerial"] = m.CaptureSerial, ["RecordingSequence"] = m.RecordingSequence,
                        ["PlaybackStatus"] = m.PlaybackStatus, ["HasCleanRange"] = m.HasCleanRange, ["HasExpandedRange"] = m.HasExpandedRange })) },
                ["messages"] = new JArray(
                    new JObject { ["role"] = "system", ["content"] = "你是录音回唱决策器，严格根据实际用户意图填写协议。" },
                    new JObject { ["role"] = "user", ["content"] = RecordingSingingDecisionCompiler.Prompt(c) }),
                ["response_format"] = RecordingSingingDecisionCompiler.ResponseFormat(c) });
        }
        File.WriteAllText(output, cases.ToString());
    }

    private static byte[] Wav(int rate, int milliseconds, int seed = 200)
    {
        int frames = rate * milliseconds / 1000; var data = new byte[44 + frames * 2];
        using (var stream = new MemoryStream(data)) using (var writer = new BinaryWriter(stream))
        { writer.Write(0x46464952); writer.Write(data.Length - 8); writer.Write(0x45564157); writer.Write(0x20746d66);
          writer.Write(16); writer.Write((short)1); writer.Write((short)1); writer.Write(rate); writer.Write(rate * 2);
          writer.Write((short)2); writer.Write((short)16); writer.Write(0x61746164); writer.Write(frames * 2);
          for (int i = 0; i < frames; i++) writer.Write((short)(i % 700 + seed)); }
        return data;
    }

#if UNITY_EDITOR
    private static void ProviderChecks()
    {
        const BindingFlags flags = BindingFlags.Instance | BindingFlags.NonPublic | BindingFlags.Public;
        var go = new GameObject("PCM lineage regression"); go.SetActive(false);
        try
        {
            var provider = go.AddComponent<SenseVoiceSpeechToText>(); var type = typeof(SenseVoiceSpeechToText);
            object Call(string name, params object[] args) => type.GetMethod(name, flags).Invoke(provider, args);
            provider.BeginLiveRecordingCandidateSession(); int first = provider.InputCaptureSessionSerial;
            provider.BeginLiveRecordingCandidateSession(); int second = provider.InputCaptureSessionSerial;
            provider.SetInputCaptureOverlap(first, 3);
            var old = (JObject)Call("DescribeRecordingPcmLineage", second, 4.0);
            Check(old["regions"].Count() == 2, "actual provider capture binding reaches semantic facts helper");
            byte[] mixed = Wav(16000, 4000);
            Call("RegisterRecordingPcmLineage", mixed, second);
            Check((int)WaveformTrace.Describe(mixed)["regions"][0]["captureSerial"] == first, "ASR actual upload trace shows original ancestor capture");
            Call("ObserveCaptureIsolation", first, true, "self-speech", 3f);
            object[] args = { second, mixed, 0f };
            Check((bool)Call("IsolateContinuationAudio", args), "late self-speech leaves fresh suffix usable");
            var suffix = (JObject)Call("DescribeRecordingPcmLineage", second, 1.0);
            Check(Source(suffix) != Source(old) && suffix["regions"].Count() == 1, "isolated suffix is not mapped back to rejected original prefix");
            object[] repeated = { second, mixed, 0f }; Call("IsolateContinuationAudio", repeated);
            Check(Source((JObject)Call("DescribeRecordingPcmLineage", second, 1.0)) == Source(suffix), "same isolation crop is identity-idempotent");
            Check((int)WaveformTrace.Describe((byte[])args[1])["regions"][0]["captureSerial"] == second,
                "actual cropped WAV gets fresh source rather than retired ancestor");

            string Retain(int capture, byte[] wav, float seconds)
            {
                var evidenceType = type.GetNestedType("SingingEvidenceSnapshot", flags);
                object evidence = Activator.CreateInstance(evidenceType, true);
                void Set(string name, object value) { if (name == "RawWavBytes") evidenceType.GetProperty(name, flags).SetValue(evidence, value); else evidenceType.GetField(name, flags).SetValue(evidence, value); }
                Set("CaptureSessionSerial", capture); Set("RawWavBytes", (byte[])wav.Clone()); Set("RawSeconds", seconds);
                Set("Text", "same lyric from separate recording evidence"); Set("SingingText", "same lyric");
                Set("Language", "ja"); Set("PitchTimelineMidi", Enumerable.Repeat(60f, (int)(seconds * 10)).ToArray());
                Set("FrameSeconds", .1f); Set("CleanEndSeconds", seconds); Set("RecoveryEndSeconds", seconds);
                type.GetField("m_LastSingingEvidence", flags).SetValue(provider, evidence);
                Check(provider.RetainCurrentSingingEvidenceClip(true), "actual provider retains recording evidence");
                var candidates = (IList)type.GetField("m_QuarantinedSingingCandidates", flags).GetValue(provider);
                var candidate = candidates[candidates.Count - 1]; var phrase = candidate.GetType().GetField("Phrase", flags).GetValue(candidate);
                string clip = (string)phrase.GetType().GetField("ClipRef", flags).GetValue(phrase);
                Check(provider.TryPrepareSingingClip(clip, true, "clean", out _, out string failure), "actual source prepares: " + failure);
                return clip;
            }
            provider.BeginLiveRecordingCandidateSession(); int song = provider.InputCaptureSessionSerial;
            byte[] original = Wav(16000, 3000, 400); Call("RegisterRecordingPcmLineage", original, song);
            string firstClip = Retain(song, original, 3);
            provider.BeginLiveRecordingCandidateSession(); int continuation = provider.InputCaptureSessionSerial;
            provider.SetInputCaptureOverlap(song, 3);
            byte[] continued = Wav(16000, 4000, 400); Call("RegisterRecordingPcmLineage", continued, continuation);
            string continuedClip = Retain(continuation, continued, 4);
            var facts = JObject.FromObject(provider.DescribeRecordingSingingDecisionFacts(continuedClip));
            string Order(string clip)
            { if (!provider.TryResolveSingingClip(clip, out int stable, out _)) throw new InvalidOperationException("prepared clip missing"); return "stable:" + stable; }
            Check(facts["pcmLineage"]["regions"].Count() == 2 && (int)facts["pcmLineage"]["regions"][0]["sourceCaptureSerial"] == song,
                "real material fact snapshot exposes the retained shared prefix");
            Check(!provider.TryBuildSingingPracticeComposition(1, 60, out _, out string conflict, Order(firstClip) + "," + Order(continuedClip)) &&
                conflict.StartsWith("recording-overlapping-continuation-selection"), "actual composition refuses two copied-prefix clip aliases before conversion/playback");
            Check(provider.TryBuildSingingPracticeComposition(1, 60, out _, out _, Order(continuedClip)), "complete continued source alone still composes");
            Check(provider.TryBuildSingingPracticeComposition(1, 60, out _, out _, Order(continuedClip) + "," + Order(continuedClip)),
                "same stable source repeated remains available to independently authorized repeat");
            provider.BeginLiveRecordingCandidateSession(); int independent = provider.InputCaptureSessionSerial;
            byte[] newSong = Wav(12000, 3500); Call("RegisterRecordingPcmLineage", newSong, independent);
            string newClip = Retain(independent, newSong, 3.5f);
            Check(provider.TryBuildSingingPracticeComposition(1, 60, out _, out _, Order(continuedClip) + "," + Order(newClip)),
                "real independent same-lyric recording remains composable");
        }
        finally { UnityEngine.Object.DestroyImmediate(go); }
    }
#endif
